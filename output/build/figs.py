import numpy as np, matplotlib
matplotlib.use('svg')
import matplotlib.pyplot as plt
plt.rcParams.update({'font.family':'serif','mathtext.fontset':'cm','svg.fonttype':'path','font.size':11})
def axes(ax,xl,yl):
    ax.set_xlim(*xl); ax.set_ylim(*yl); ax.set_aspect('equal')
    for s in ax.spines.values(): s.set_visible(False)
    ax.set_xticks([]); ax.set_yticks([])
    ax.annotate('',xy=(xl[1],0),xytext=(xl[0],0),arrowprops=dict(arrowstyle='-|>',lw=0.8,color='k',mutation_scale=8))
    ax.annotate('',xy=(0,yl[1]),xytext=(0,yl[0]),arrowprops=dict(arrowstyle='-|>',lw=0.8,color='k',mutation_scale=8))
    ax.text(xl[1]-0.05,-0.12,'$x$',ha='right',va='top'); ax.text(0.1,yl[1]-0.05,'$y$',ha='left',va='top')
    ax.text(-0.08,-0.1,'O',ha='right',va='top',family='DejaVu Sans',fontsize=10)
# fig 8
fig,ax=plt.subplots(figsize=(2.9,2.75))
axes(ax,(-2.7,2.4),(-1.5,4.4))
xs=np.linspace(-2.45,1,200); ax.plot(xs,xs**2+2*xs,'k',lw=1.2)
xs=np.linspace(1,1.42,50); ax.plot(xs,3*xs,'k',lw=1.2)
ax.plot([1,1],[0,3],'k--',lw=0.6); ax.plot([0,1],[3,3],'k--',lw=0.6)
ax.plot([1],[3],'ko',ms=3)
ax.plot([-1,-1],[0,-1],'k--',lw=0.6); ax.plot([-1,0],[-1,-1],'k--',lw=0.6)
ax.text(1,-0.12,'$1$',ha='center',va='top'); ax.text(-0.1,3,'$3$',ha='right',va='center')
ax.text(-2,0.12,'$-2$',ha='center',va='bottom'); ax.text(-1,0.12,'$-1$',ha='center',va='bottom')
ax.text(0.1,-1,'$-1$',ha='left',va='center')
ax.text(1.5,4.1,'$y=f(x)$',ha='left',va='center',fontsize=10)
fig.savefig('fig8.svg',bbox_inches='tight',pad_inches=0.02,transparent=False,facecolor='white')
